<?php

namespace Tests\Unit\Services\Mail;

use App\Services\Mail\Routing\Handlers\LinkedThreadHandler;
use PHPUnit\Framework\TestCase;

/**
 * Плашка «возможно новая заявка» не ставится на просьбу поправить КП/счёт (29.10.2026).
 * Тексты — собственные тексты клиентов из решений, которые менеджеры отклонили или приняли.
 */
class PossibleNewRequestQuoteEditTest extends TestCase
{
    /** @return array<string, array{0:string}> */
    public static function edits(): array
    {
        return [
            'добавь в КП' => ['Добавь, пожалуйста, в КП M00217 - 1 шт Карта 20006175'],
            'актуализировать и добавить' => ['Добрый день! Прошу актуализировать это КП + добавить: 2. Эл.двигатель DC привода дверей Sematic SGF120 24V'],
            'изменения в счёт' => ['Добрый день! Прошу внести изменения в данный счет 11200: - п.2,4,5 — исключить - п.3 — увеличить кол-во до 2шт.'],
            'добавить в КП позицию' => ['Здравствуйте! Прошу добавить в КП позицию M10666- 1 шт'],
            'обновить КП и добавить' => ['Добрый день! Прошу обновить КП и добавить подшипник M07764 - 2 шт'],
            'изменения в КП №' => ['Добрый день Прошу Вас внести изменения в КП №371321 от 22.10.2026 Поз№ 2 по КП заменить на ролик'],
            'добавить в счёт' => ['Добрый день! Прошу добавить в счет: Ролик D-85мм каретки дверей KM587123G01 Kone - 10 шт.'],
            'изменить счёт' => ['Дмитрий, прошу изменить счет: добавить еще один такой же датчик и отправить на срочную комплектацию'],
        ];
    }

    /** @dataProvider edits */
    public function test_an_edit_of_the_quote_or_invoice_is_not_a_new_request(string $text): void
    {
        $this->assertTrue(LinkedThreadHandler::isQuoteEditText($text), $text);
    }

    /** @return array<string, array{0:string}> */
    public static function newAsks(): array
    {
        return [
            'нужен вот такой' => ['Добрый день, Нужен вот такой выключатель, у Вас на сайте не поняла какой. Выключатель ВП73-10432 00 УХЛЗ'],
            'можно кп на' => ['Можно кп на 1 шт KM365754G01 Спасибо'],
            'есть такое' => ['Здравствуйте, Дмитрий! Приводное колесо привода поручня эскалатора Sigma SCE D610мм Кол-во – 1 шт. Есть такое?'],
            'интересует также' => ['Владимир, добрый день! Интересует также модель "Schindler PMS420-C384-3". Пришлите, пожалуйста, по возможности КП.'],
            'требуется' => ['Требуется квш митсубиши (обод). 1 шт'],
            'следующий поручень' => ['Добрый день, Дмитрий! Следующий поручень под замену. Ждем пока КП 25 м 08 см. Спасибо.'],
        ];
    }

    /** @dataProvider newAsks */
    public function test_a_new_item_ask_is_not_an_edit(string $text): void
    {
        $this->assertFalse(LinkedThreadHandler::isQuoteEditText($text), $text);
    }
}
