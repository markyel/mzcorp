<?php

namespace Tests\Unit\Services\Mail;

use App\Services\Mail\InvoiceMentionMatcher;
use PHPUnit\Framework\TestCase;

/**
 * InvoiceMentionMatcher — единый владелец «просьба о счёте / упоминание счёта».
 * Кейсы — реальные собственные тексты клиентов из реплея 2026-09-09
 * (166 писем с цитатой нашего КП за 30 дней).
 */
class InvoiceMentionMatcherTest extends TestCase
{
    private InvoiceMentionMatcher $m;

    protected function setUp(): void
    {
        parent::setUp();
        $this->m = new InvoiceMentionMatcher;
    }

    /** @return array<string, array{0:string}> */
    public static function requests(): array
    {
        return [
            'выставьте, пожалуйста' => ['Алексей, добрый день! Выставьте, пожалуйста, счет. Сегодня оплатим.'],
            'прошу счёт + артикул' => ['Прошу счёт M12684 - 2шт'],
            'можно счет и спецку' => ['Добрый день Можно счет и спецку?'],
            'можно пожалуйста счёт' => ['Добрый день! Сергей, можно пожалуйста счёт'],
            'прошу направить счет' => ['Добрый день. Прошу направить счет.'],
            'счет на товар + КП' => ['Добрый день Счет на Табло панели приказов CPI18B FAA25100AA2 Otis – 1 шт Коммерческое предложение №364765 от 20 августа 2026'],
            'выпишите счёт по КП' => ['Выпишите пожалуйста счёт по коммерческому предложению №364355 от 17 августа 2026г.'],
            'выписать счет' => ['Выписать счет по КП № 365334 Плата-репитер'],
            'пришли, пожалуйста, счет' => ['Привет. Пришли, пожалуйста, счет Карта 20006175'],
            'выстави, пожалуйста' => ['Илья, добрый день. Выстави, пожалуйста, счет. Реквизиты прилагаю.'],
            'пришлите пожалста' => ['Здравствуйте, пришлите пожалста счет с учетом доставки по этому КП'],
            'обнови счет' => ['Илья, обнови, пожалуйста, счет. Игорь'],
            'прошу счет, шлейф' => ['Добрый день Прошу счет, шлейф нужен на 2м'],
            'пришлите счет на устройство' => ['Пришлите, пожалуйста, счет на грузовзвешивающее устройство и на фотобарьер.'],
            'поправить счет (тема)' => ["Прошу поправить счет 366414\nНадо исправить Цепь одна 1 шт. И добавить доставку."],
            'счет на 12 демпферов' => ['Пришлите счет на 12 демпферов'],
            'прошу прислать счёт на оплату' => ['Прошу прислать счёт на оплату по КП'],
            'нужен счет' => ['Привет Алексей! Нужен счет по этому КП.'],
        ];
    }

    /** @dataProvider requests */
    public function test_requests_invoice(string $text): void
    {
        $this->assertTrue($this->m->requestsInvoice($text), $text);
    }

    /** @return array<string, array{0:string}> */
    public static function notRequests(): array
    {
        return [
            'реквизит выставленного счёта + отгрузка' => ["Счет на оплату No 3228 от 25 марта 2026\nПрошу сообщить дату отгрузки!"],
            'когда получим по счету' => ['Здравствуйте, Дмитрий. Когда получим изд-я по счету(во вложении)?'],
            'дата готовности по счету' => ['Прошу уточнить дату готовности заказа по счету: Счет на оплату № 6811'],
            'спецификацию на данный счет' => ['Добрый день! Прошу направить спецификацию на данный счет.'],
            'счет согласован, отгрузка' => ['Дмитрий, счет №8919 — согласован. Прошу взять в работу и подготовить к отгрузке.'],
            'оплата произведена' => ['Оплата по данному счёту произведена. Заказчик просит заключить договор.'],
            'ждем отгрузки по счету' => ['Ждем отгрузки платы по счету № 6488 от 22 июня 2026г.'],
            'аннулировали документы по счету' => ['Просьба уточнить почему аннулировали документы по счету 7933.'],
            'счёт-фактура' => ['Пришлите, пожалуйста, счёт-фактуру и УПД по отгрузке.'],
            'информацию по счету' => ['подскажите информацию по счету № 5730 от 01 июня 2026'],
            'не пришел заказ' => ['Добрый день, Дмитрий! Не пришел заказ № 6892?'],
        ];
    }

    /** @dataProvider notRequests */
    public function test_does_not_request_invoice(string $text): void
    {
        $this->assertFalse($this->m->requestsInvoice($text), $text);
    }

    public function test_intends_to_pay(): void
    {
        $this->assertTrue($this->m->intendsToPay('Добрый день, счет актуален ? будем оплачивать сегодня !'));
        $this->assertTrue($this->m->intendsToPay('Вот это КП готовы оплачивать. Только добавьте канаты'));
        $this->assertTrue($this->m->intendsToPay('сегодня согласование, если все норм, завтра оплата Вам и сами заберем!'));
        $this->assertFalse($this->m->intendsToPay('Оплата по данному счёту произведена.'));
        $this->assertFalse($this->m->intendsToPay('Когда планируется прибытие товара по счету № 6141?'));
    }

    public function test_mentions_and_issued_reference(): void
    {
        $this->assertTrue($this->m->mentions('по счету 6012 не присылали ссылки'));
        $this->assertFalse($this->m->mentions('Подскажите срок гарантии на редуктор'));
        $this->assertTrue($this->m->referencesIssuedInvoice('Счет на оплату № 8249 от 07.08.2026'));
        $this->assertFalse($this->m->referencesIssuedInvoice('Пришлите счет на оплату'));
    }
}
