<?php

namespace App\Services\Mail;

/**
 * Единый владелец понятия «упоминание / просьба счёта» в тексте клиента
 * (2026-09-09). До этого одно и то же считали четыре регулярки в четырёх
 * классах (PostSaleFulfillmentDetector, CitedOutboundQuoteRouter,
 * InboundIntentClassifier, PaymentDocumentDetector) и расходились в вердикте.
 *
 * Три разных вопроса — три метода, не путать:
 *  - mentions()                — в тексте вообще есть слово «счёт/оплата/invoice»
 *                                (слабый сигнал: cap уверенности LLM-интента);
 *  - referencesIssuedInvoice() — упоминание УЖЕ ВЫСТАВЛЕННОГО документа
 *                                («Счёт на оплату № 3228 от 25 марта») — реквизит,
 *                                не просьба;
 *  - requestsInvoice()         — клиент ПРОСИТ выставить/прислать счёт или счёт
 *                                на количество — инициируется продажа.
 *
 * Текст на вход — собственный текст клиента (EmailTextCleanerService::clientOwnText)
 * плюс тема; регистр не важен. Чистый класс без зависимостей — покрыт unit-тестами.
 */
final class InvoiceMentionMatcher
{
    /** Слабое упоминание счёта/оплаты. */
    private const MENTION_RE = '/сч[её]т|на\s+оплат|invoice|инвойс/iu';

    /**
     * Просьба + «счёт»: «выставьте, пожалуйста, счёт», «прошу направить счёт»,
     * «можно счёт и спецку?», «выпишите счёт», «нужен счёт», «пришли счёт».
     * Между глаголом и «счёт» допускаются запятые, «пожалуйста», «нам», «новый».
     * Реплей 2026-09-09 по 166 письмам с цитатой КП: без этих форм терялась
     * половина настоящих просьб.
     */
    private const REQUEST_VERB_RE = '/(выстав\w*|перевыстав\w*|пришл\w*|присла\w*|присыл\w*|вышл\w*|выслать|высыл\w*|направ\w*|выпис\w*|выпиш\w*|оформ\w*|подготов\w*|обнов\w*|актуализ\w*|поправ\w*|исправ\w*|скорректир\w*|сдела\w*|дайте|дать|получить|прошу|просьба|просим|можно|нужен|нужна|нужно|ждём|ждем|хотим|хотел\w*)[\s,]*(?:(?:пожалуйста|пожалста|пж|плз|ли|бы|нам|мне|новый|актуальный|ещё|еще|один|такой\s+же)[\s,]*)*сч[её]т/u';

    /**
     * Намерение оплатить по цитируемому КП/счёту: «будем оплачивать», «готовы
     * оплатить», «оплатим сегодня», «завтра оплата Вам», «к оплате».
     */
    private const PAY_INTENT_RE = '/оплатим|будем\s+оплачивать|готов\w*\s+(к\s+)?опла[тч]\w*|можно\s+(ли\s+)?(произвести\s+)?оплат\w*|к\s+оплате|в\s+оплату|на\s+оплату\s+(отправ|пошл|пойд|уш[её]л|ушл)|(завтра|сегодня|на\s+днях)\s+оплат\w*|оплат\w*\s+(вам|завтра|сегодня|на\s+днях|будет|пройд\w*|пойд\w*)/u';

    /**
     * Ссылка на выставленный документ: «счёт на оплату № 3228», «счёт на оплату
     * no 3228 от 25 марта 2026», «счёт на оплату 4679 от 04 мая» (без знака №,
     * но с датой «от …»).
     */
    private const ISSUED_DOC_REF_RE = '/сч[её]т\s+на\s+оплату\s*(?:(?:№|no\.?|n|#)\s*[\w\-\/]*\d[\w\-\/]*|[\w\-\/]*\d[\w\-\/]*(?=\s+от\s+\d))/u';

    /**
     * «Счёт на оплату» / «счёт на 12 …» / «Счёт на Табло … КП №364765» без глагола —
     * тоже просьба (после вырезания реквизитов выставленных документов).
     * «по счёту на …» — ссылка на существующий счёт, не просьба.
     */
    private const BARE_REQUEST_RE = '/(?<!по\s)(?<!по)\bсч[её]т\s+(?:на\s+(?:оплат|\d|[a-zа-яё])|по\s+(?:кп\b|коммерческ\w*\s+предложени\w*|данному\s+кп))/u';

    public function mentions(string $text): bool
    {
        return preg_match(self::MENTION_RE, $text) === 1;
    }

    public function referencesIssuedInvoice(string $text): bool
    {
        return preg_match(self::ISSUED_DOC_REF_RE, mb_strtolower($text)) === 1;
    }

    /**
     * Клиент просит счёт (продажа). «Счёт-фактура» — закрывающий документ, не
     * считается; ссылка на уже выставленный счёт — реквизит, не считается.
     * Кейсы: esc@interlift.su «Пришлите счет на 12 демпферов…»; ЗИПИС/M00965
     * «Прошу прислать счёт на оплату…»; M-2026-14524 «Счет на оплату No 3228 от
     * 25 марта 2026 / Прошу сообщить дату отгрузки» — НЕ просьба.
     */
    public function requestsInvoice(string $text): bool
    {
        $h = mb_strtolower($text);

        // «счёт-фактура» — закрывающий документ, не запрос счёта на оплату.
        $h = (string) preg_replace('/сч[её]т[-\s]*фактур\w*/u', ' ', $h);

        // Глагол-просьба непосредственно перед «счёт» — сильный сигнал, проверяем
        // ДО вырезания ссылок на документ: «прошу обновить счёт на оплату № 3674»
        // — это просьба перевыставить счёт, номер тут не мешает.
        if (preg_match(self::REQUEST_VERB_RE, $h) === 1) {
            return true;
        }

        // Ссылка на УЖЕ ВЫСТАВЛЕННЫЙ документ вырезается — это реквизит письма
        // (Liftway-saas и 1С ставят такую строку первой в теле).
        $h = (string) preg_replace(self::ISSUED_DOC_REF_RE, ' ', $h);

        return preg_match(self::BARE_REQUEST_RE, $h) === 1;
    }

    /** Клиент собирается оплатить по цитируемому КП/счёту («будем оплачивать», «готовы оплатить»). */
    public function intendsToPay(string $text): bool
    {
        return preg_match(self::PAY_INTENT_RE, mb_strtolower($text)) === 1;
    }

    /**
     * Для роутера цитат нашего КП: клиент либо просит счёт, либо собирается
     * платить — обе ситуации переводят заявку в «ждёт счёт».
     */
    public function requestsInvoiceOrIntendsToPay(string $text): bool
    {
        return $this->requestsInvoice($text) || $this->intendsToPay($text);
    }
}
