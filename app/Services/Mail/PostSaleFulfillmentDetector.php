<?php

namespace App\Services\Mail;

use App\Models\EmailMessage;

/**
 * Pre-classifier: письмо-просьба отгрузить / поставить на комплектацию уже
 * оформленный заказ — это post_sale, а не новая заявка.
 *
 * gpt-4o на терсовых письмах («Прошу поставить на комплектацию», тема
 * «Отгрузка», вложение-zip с платёжкой) систематически ставит client_request
 * («комплектация → запрос ТМЦ», «вложение может быть спецификацией») →
 * плодятся ошибочные заявки с назначением менеджера (тикеты M-2026-2706,
 * M-2026-2762). Промпт это не лечит — модель упорно держит client_request.
 *
 * ВАЖНО (фидбэк по тикету): информации из самого письма достаточно, чтобы
 * понять что это НЕ новая заявка — анализировать вложения и искать оплаченный
 * заказ не нужно. Сигнал — тема «Отгрузка» и/или тело «прошу поставить на
 * комплектацию / отгрузите». Поэтому детектор работает ТОЛЬКО по контенту:
 *
 *   1) тема содержит «отгрузк…» ЛИБО тело содержит лексику отгрузки/
 *      комплектации купленного («на комплектаци…», «отгруз…»);
 *   2) НЕТ признаков НОВОГО запроса — цены/КП или перечня с количествами
 *      (защита от «отгрузите образцы и заодно посчитайте КП на 50 роликов»).
 *
 * Заказ детектор НЕ ищет и письмо ни к чему не привязывает: в архиве могут
 * быть платёжки по разным счетам — угадывать конкретный заказ нельзя. Такое
 * письмо правильно оставить в общем ящике (info@) нетронутым, без заявки.
 */
class PostSaleFulfillmentDetector
{
    /** Лексика отгрузки/комплектации в теме письма. */
    private const SUBJECT_STEMS = ['отгрузк'];

    /** Лексика отгрузки/комплектации купленного в теле письма. */
    private const BODY_STEMS = ['на комплектаци', 'отгруз'];

    /**
     * Признаки НОВОГО запроса (цена/КП/перечень с количествами). Если хоть
     * один найден — это не чистая отгрузка, отдаём решение LLM.
     */
    private const NEW_ORDER_MARKERS = [
        'коммерческое предложение',
        'пришлите кп',
        'нужно кп',
        'нужна кп',
        'дайте кп',
        'посчита',
        'просчита',
        'рассчита',
        'прайс',
        'стоимост',
        'почём',
        'почем',
        'цена',
        'цену',
        'цены',
        'штук',
        // Явный запрос выставить счёт = инициируется продажа → это НОВАЯ
        // заявка, а не отгрузка уже оплаченного заказа. Тикет: «Прошу
        // выставить счёт и поставить на комплектацию: M12243 — 5шт».
        'выставить сч',
        'выставите сч',
        'выставьте сч',
    ];

    /**
     * Лексика «закрывающие документы / реквизиты» — постпродажный документо-
     * оборот по СОСТОЯВШЕЙСЯ сделке. Используется ТОЛЬКО в контексте, где сделка
     * уже подтверждена (ответ в закрытый тред + у клиента есть оплаченный заказ,
     * см. detectDocsOrFulfillment) — в общем inbox эти слова слишком общие.
     */
    private const DOCS_STEMS = [
        'реквизит',
        'закрывающ',       // закрывающие документы
        'упд',
        'счет-фактур', 'счёт-фактур',
        'акт сверки',
        'оригинал документ', 'оригиналы документ',
        'товарн', // товарная накладная / товарно-транспортная
    ];

    /**
     * Расширенный детект для гарда наследования: письмо в ЗАКРЫТЫЙ тред от
     * клиента с недавним оплаченным/выигранным заказом. Ловит и отгрузку
     * (detect), и документооборот по сделке (реквизиты/УПД/акты). Гварды
     * «нет признаков нового заказа» — те же.
     *
     * @return string|null  Причина либо null.
     */
    public function detectDocsOrFulfillment(EmailMessage $message): ?string
    {
        $base = $this->detect($message);
        if ($base !== null) {
            return $base;
        }

        $subject = mb_strtolower((string) $message->subject);
        $body = mb_strtolower((string) $message->body_plain);
        $haystack = $subject . "\n" . $body;

        $matched = null;
        foreach (self::DOCS_STEMS as $stem) {
            if (str_contains($haystack, $stem)) {
                $matched = $stem;
                break;
            }
        }
        if ($matched === null) {
            return null;
        }
        if (preg_match('/\d+\s*шт/u', $haystack) === 1) {
            return null;
        }
        foreach (self::NEW_ORDER_MARKERS as $marker) {
            if (str_contains($haystack, $marker)) {
                return null;
            }
        }
        if ($this->looksLikeInvoiceRequest($haystack)) {
            return null;
        }

        return "документооборот по сделке («{$matched}»), без запроса цены/КП — постпродажное письмо";
    }

    /**
     * Клиент просит выставить/прислать СЧЁТ НА ОПЛАТУ — инициируется продажа,
     * это НОВАЯ заявка (client_request), а не отгрузка/документооборот уже
     * оформленного заказа и не постпродажа. Публичный вход для пост-LLM гарда
     * в MailCategoryClassifier.
     *
     * Кейс M-2026 (M00965): «Прошу прислать счёт на оплату и поставить на
     * комплектацию по позиции …» — gpt-4o цеплялся за «комплектацию/забрать»
     * и ставил post_sale, хотя клиент явно просит счёт = хочет купить.
     */
    public function requestsInvoiceToPay(EmailMessage $message): bool
    {
        // Только СВЕЖИЙ текст письма (без цитаты старой переписки): «выставить/
        // прислать счёт» из ЦИТАТЫ прошлого письма НЕ означает, что клиент просит
        // счёт СЕЙЧАС. Кейс M-2026-10660: новое письмо «Отправили нам заказ?»
        // (постпродажа), а «счёт» был в цитате → override ложно флипал в
        // client_request.
        $fresh = $this->freshText($message);
        $haystack = mb_strtolower((string) $message->subject . "\n" . $fresh);

        return $this->looksLikeInvoiceRequest($haystack);
    }

    /** Лексика «статус/отгрузка/самовывоз/возврат уже размещённого заказа». */
    private const DELIVERY_STATUS_RE = '/отправили\s+(ли\s+)?(нам\s+)?(заказ|товар|посылк)|отгрузили\s+ли|дат\w*\s+(поступлени|отгрузк|отправк)|статус\s+(заказа|отгрузк\w+|поставк\w+|доставк\w+)|заказ\s+готов|готов\s+ли\s+заказ|получен\w*\s+(ли\s+)?оплат|возможн\w+\s+забрать|забрать\s+(товар|заказ|со\s+склад)|возврат\s+(по\s+)?(сч[её]т|заказ)/iu';

    /** Reply-контекст: вопрос о сроках/доставке уже размещённого заказа. */
    private const REPLY_DELIVERY_RE = '/срок\w*\s+поставк|когда\s+(будет|поставите|отгруз\w+|отправ\w+|привез\w+|прид[её]т|приход\w+)/iu';

    /**
     * Клиент спрашивает про СТАТУС уже размещённого заказа (отправили ли, дата
     * поступления, статус отгрузки) — это ПОСТПРОДАЖА, а не новая заявка. По
     * СВЕЖЕМУ тексту (без цитаты). Гард от нового заказа: если просят цену/КП —
     * не считаем (это уже новый запрос).
     * Кейсы: liftway «уточнить дату поступления по Счёт 3228» (M-2026-10799),
     * import-lift «Отправили нам заказ?» (M-2026-10660).
     */
    public function deliveryStatusInquiry(EmailMessage $message): bool
    {
        $haystack = mb_strtolower((string) $message->subject . "\n" . $this->freshText($message));

        // Гард нового заказа: просят просчитать/цену/КП → это новый запрос, не
        // статус (проверяем первым, чтобы не спутать).
        foreach (['посчита', 'просчита', 'рассчита', 'прайс', 'стоимост', 'коммерческое предложение', 'пришлите кп', 'нужно кп', 'нужна кп'] as $marker) {
            if (str_contains($haystack, $marker)) {
                return false;
            }
        }

        // Явные постпродажные сигналы (статус/отгрузка/самовывоз/возврат).
        if (preg_match(self::DELIVERY_STATUS_RE, $haystack) === 1) {
            return true;
        }

        // Reply-контекст: «срок поставки / когда отгрузите» в ОТВЕТЕ (Re:/Fwd:
        // или in_reply_to) про уже размещённый заказ. В первичном письме такая
        // фраза может быть пресейлом, поэтому только в ответах.
        $isReply = ! empty($message->in_reply_to)
            || preg_match('/^\s*(re|fwd|fw|ответ)\b/iu', (string) $message->subject) === 1;
        if ($isReply && preg_match(self::REPLY_DELIVERY_RE, $haystack) === 1) {
            return true;
        }

        return false;
    }

    /** Свежий текст письма без хвоста цитаты. Fail-soft. */
    private function freshText(EmailMessage $message): string
    {
        $body = (string) $message->body_plain;
        try {
            return app(EmailTextCleanerService::class)->cutOwnQuotedTail($body);
        } catch (\Throwable $e) {
            return $body;
        }
    }

    /**
     * Запрос ВЫСТАВИТЬ / ПРИСЛАТЬ счёт на оплату (или на количество товара) —
     * инициируется продажа. Ловит «счёт на оплату», «счёт на 12 …», а также
     * явные глаголы-просьбы «выставить/прислать/выслать/оформить/подготовить
     * счёт». НЕ матчит «счёт-фактуру» (закрывающий документ по состоявшейся
     * сделке) — вырезаем её перед проверкой.
     * Кейсы: esc@interlift.su «Пришлите счет на 12 демпферов…»; ЗИПИС/M00965
     * «Прошу прислать счёт на оплату…».
     */
    private function looksLikeInvoiceRequest(string $haystack): bool
    {
        // «счёт-фактура» — закрывающий документ, не запрос счёта на оплату.
        $h = preg_replace('/сч[её]т[-\s]*фактур\w*/u', ' ', $haystack);

        // Глагол-просьба непосредственно перед «счёт» — сильный сигнал, проверяем
        // ДО вырезания ссылок на документ: «прошу обновить счёт на оплату № 3674»
        // — это просьба перевыставить счёт (продажа), номер тут не мешает.
        if (preg_match(self::INVOICE_REQUEST_VERB_RE, $h) === 1) {
            return true;
        }

        // Ссылка на УЖЕ ВЫСТАВЛЕННЫЙ документ — «Счёт на оплату № 3228 от 25
        // марта 2026» — это не просьба, а реквизит письма (шапка/цитата номера).
        // Liftway-saas и 1С ставят такую строку первой в теле. Без вырезания
        // фраза «счёт на оплату» ловилась как запрос счёта, override флипал
        // post_sale→client_request, и вопрос «сообщите дату отгрузки» по
        // мартовскому счёту рождал пустую заявку (M-2026-14524; за 30 дней —
        // 13 таких писем, 6 заявок-фантомов).
        $h = preg_replace(self::INVOICE_DOC_REF_RE, ' ', $h);

        return preg_match('/сч[её]т\s+на\s+(оплат|\d)/u', $h) === 1;
    }

    /** Глагол-просьба + «счёт»: выставить/прислать/выслать/оформить/подготовить/обновить счёт. */
    private const INVOICE_REQUEST_VERB_RE = '/(выстав\w+|пришл\w+|присла\w+|вышл\w+|выслать|оформ\w+|подготов\w+|обнов\w+)\s+сч[её]т/u';

    /**
     * Ссылка на выставленный документ: «счёт на оплату № 3228», «счёт на оплату
     * no 3228 от 25 марта 2026», «счёт на оплату 4679 от 04 мая» (без знака №,
     * но с датой «от …»). Haystack уже в нижнем регистре.
     */
    private const INVOICE_DOC_REF_RE = '/сч[её]т\s+на\s+оплату\s*(?:(?:№|no\.?|n|#)\s*[\w\-\/]*\d[\w\-\/]*|[\w\-\/]*\d[\w\-\/]*(?=\s+от\s+\d))/u';

    /**
     * @return string|null  Причина (для лога/reasoning) либо null — паттерн не сработал.
     */
    public function detect(EmailMessage $message): ?string
    {
        // Запрос статуса уже размещённого заказа (отправили ли / дата поступления
        // / статус отгрузки) — постпродажа, не новая заявка. Считаем по свежему
        // тексту, с гардом от нового заказа (см. deliveryStatusInquiry).
        if ($this->deliveryStatusInquiry($message)) {
            return 'запрос статуса доставки/отгрузки уже размещённого заказа — постпродажа';
        }

        $subject = mb_strtolower((string) $message->subject);
        $body = mb_strtolower((string) $message->body_plain);
        $haystack = $subject . "\n" . $body;

        $matchedSignal = null;
        foreach (self::SUBJECT_STEMS as $stem) {
            if (str_contains($subject, $stem)) {
                $matchedSignal = 'тема об отгрузке';
                break;
            }
        }
        if ($matchedSignal === null) {
            foreach (self::BODY_STEMS as $stem) {
                if (str_contains($body, $stem)) {
                    $matchedSignal = 'текст об отгрузке/комплектации';
                    break;
                }
            }
        }
        if ($matchedSignal === null) {
            return null;
        }

        // Перечень с количествами (в т.ч. склеенный с цифрой — «5шт.») —
        // признак НОВОГО заказа, а не чистой отгрузки. str_contains(' шт')
        // такое не ловил (требовал пробел), поэтому отдельная regex-проверка.
        if (preg_match('/\d+\s*шт/u', $haystack) === 1) {
            return null;
        }

        foreach (self::NEW_ORDER_MARKERS as $marker) {
            if (str_contains($haystack, $marker)) {
                return null;
            }
        }
        if ($this->looksLikeInvoiceRequest($haystack)) {
            return null;
        }

        return $matchedSignal . ' уже оформленного заказа, без запроса цены/КП — постпродажное письмо, не новая заявка';
    }
}
