<?php

namespace App\Prompts\Request;

/**
 * Переоценка статуса «застрявшей» заявки по ВСЕЙ переписке с клиентом.
 * Задача LLM — понять, ЧЕЙ ХОД (за клиентом или за нами), т.к. многие заявки
 * висят в менеджерских статусах (in_progress/assigned) и числятся «просрочкой
 * менеджера», хотя по факту мы задали вопрос / прислали КП / счёт, а клиент
 * молчит. Если ход за клиентом — заявку нужно перевести в waiting-on-client
 * статус (дальше её подхватит штатное авто-закрытие по таймауту).
 *
 * gpt-4o-mini, JSON-режим.
 */
class ReassessRequestStatusPrompt
{
    /**
     * @return array<int, array{role: string, content: string}>
     */
    public function build(string $currentStatus, string $transcript): array
    {
        $system = <<<'SYS'
Ты анализируешь переписку с клиентом по заявке на запчасти и определяешь, ЧЕЙ
ХОД сейчас — за клиентом или за нами (поставщиком «Мой Лифт»). Заявка сейчас в
менеджерском статусе (мы якобы работаем), но часто ход давно за клиентом.

Дана хронология переписки: направление (ОТ НАС / ОТ КЛИЕНТА), дата, текст.

Определи ball_with:
- "client" — ПОСЛЕДНЕЕ содержательное действие за НАМИ, и мы ждём ответа/решения
  клиента, а он молчит. Примеры: мы задали вопрос («аналоги рассматриваем?»,
  «уточните модель», «пришлите фото/чертёж», «какой номер лифта?»); мы прислали
  КП/цену и ждём решения; мы выставили счёт и ждём оплаты; мы дали информацию и
  ждём подтверждения. Ход за клиентом.
- "us" — ПОСЛЕДНЕЕ письмо от КЛИЕНТА и требует НАШЕГО действия: клиент задал
  вопрос, прислал уточнение/данные, попросил КП/счёт, согласовал — а мы не
  ответили. Ход за нами (реальная просрочка).
- "unclear" — по переписке невозможно уверенно определить.

Если ball_with = "client", выбери target_status:
- "awaiting_client_clarification" — мы задали клиенту ВОПРОС или запросили данные
  (модель, фото, номер лифта, подтверждение аналога и т.п.).
- "quoted" — мы отправили КП / ценовое предложение и ждём решения.
- "invoiced" — мы выставили счёт и ждём оплаты.
Иначе (ball_with = "us"/"unclear") target_status = null.

Правила:
- Смотри на ПОСЛЕДНЕЕ содержательное сообщение (игнорируй подписи, авто-цитаты).
- Обещания С НАШЕЙ стороны («направлю КП позже», «уточню и вернусь») — ход за
  НАМИ (us), а не за клиентом.
- Не выдумывай: если сигналов мало — "unclear", confidence низкий.
- Короткий вопрос («аналоги рассматриваем?») — это clarification, ход за клиентом.

Верни СТРОГО JSON:
{"ball_with":"client|us|unclear","target_status":"awaiting_client_clarification|quoted|invoiced|null","confidence":0.0,"reasoning":"кратко по-русски"}
SYS;

        $user = "Текущий статус заявки: {$currentStatus}\n\nПЕРЕПИСКА (хронология):\n{$transcript}";

        return [
            ['role' => 'system', 'content' => $system],
            ['role' => 'user', 'content' => $user],
        ];
    }
}
