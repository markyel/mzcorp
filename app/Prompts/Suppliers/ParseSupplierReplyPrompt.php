<?php

namespace App\Prompts\Suppliers;

/**
 * Промпт разбора ответа поставщика на наш запрос расценки (Фаза 3.3).
 * Мы ЗНАЕМ запрошенные позиции (передаём нумерованным списком) — задача LLM
 * сопоставить ответ поставщика с ними: для каждой позиции исход
 * quoted / refused / skipped. Цена/валюта/срок — как в ответе, без интерпретации.
 *
 * gpt-4o-mini, JSON-режим.
 */
class ParseSupplierReplyPrompt
{
    private const MAX_BODY_CHARS = 8000;
    private const MAX_ATTACHMENT_CHARS = 14000;

    /**
     * @param  array<int, array{index:int, name:string, oem:?string, qty:?string}>  $items
     * @param  string  $attachmentText  текст из вложений (прайс PDF/Excel/Word)
     * @param  array<int, string>  $images  data:image/...;base64 страницы PDF / фото прайса
     * @return array<int, array{role: string, content: mixed}>
     */
    public function build(array $items, string $replyText, string $attachmentText = '', array $images = []): array
    {
        $replyText = mb_substr(trim($replyText), 0, self::MAX_BODY_CHARS);
        $attachmentText = mb_substr(trim($attachmentText), 0, self::MAX_ATTACHMENT_CHARS);

        $itemsBlock = '';
        foreach ($items as $it) {
            $meta = trim(implode(' · ', array_filter([$it['oem'] ?? null, $it['qty'] ?? null])));
            $itemsBlock .= sprintf("%d. %s%s\n", $it['index'], $it['name'], $meta !== '' ? " ({$meta})" : '');
        }

        $system = <<<'SYS'
Тебе дан СПИСОК ПОЗИЦИЙ, которые мы запросили у поставщика, и ЕГО ОТВЕТ (текст
письма и/или приложенный прайс — текстом из файла и/или изображениями страниц).
Сопоставь ответ с позициями по номеру/названию/артикулу. Для КАЖДОЙ позиции
из списка верни исход:

- "quoted"  — поставщик дал цену. Заполни price (число, без валюты и пробелов),
              currency (как в ответе: «руб», «USD», «EUR»… если есть),
              valid_until_text (срок поставки/действия как в тексте, если есть),
              quote (краткая цитата из ответа/прайса по этой позиции).
              Аналог/замена/альтернатива С ЦЕНОЙ — это ТОЖЕ "quoted" (в quote
              отметь, что предложен аналог).
- "refused" — поставщик явно отказал по позиции («нет», «снято с производства»,
              «не поставляем», «нет в наличии») И цены не дал. Заполни
              refusal_reason (кратко) + quote.
- "skipped" — позиция в ответе НЕ упомянута (молчание). Ничего не заполняй.

Правила:
- ЕСТЬ ЧИСЛОВАЯ ЦЕНА по позиции ⇒ исход ВСЕГДА "quoted", даже если товар описан
  как «аналог», «альтернатива», «замена», «под заказ», «оригинал». "refused" —
  ТОЛЬКО когда цены НЕТ и есть явный отказ.
- Слова «аналог»/«альтернатива»/«замена» САМИ ПО СЕБЕ отказом НЕ являются — часто
  это часть НАЗВАНИЯ позиции (напр. «Плата DHG-162 (альтернатива для DHG-160)»),
  а не заявление поставщика. Смотри, есть ли рядом цена.
- «NO.» / «No.» / «№» / «#» — это ЗАГОЛОВОК КОЛОНКИ НОМЕРА строки (обычно рядом с
  «ITEM», «OEM», «BRAND», «QTY»), а НЕ отказ. Английское «no/NO» считается отказом
  ТОЛЬКО как явное «not available / no stock / out of stock / we can't supply» по
  позиции И БЕЗ цены. Если в той же строке/ответе есть цена — исход "quoted".
- Цена часто пишется СЛИТНО с валютой и единицей: «USD860.00/PC», «$860/pc»,
  «USD 860.00 / шт», «EUR 1 200/set». Извлеки число (860.00) и currency (USD);
  «/PC», «/pc», «/шт», «per pc», «за шт» — это цена ЗА ЕДИНИЦУ, всё равно "quoted".
- price — только число (point как десятичный разделитель), без валюты/пробелов/«руб».
- currency нормализуй: «долл»/«$»/«долларов»/«USD» → "USD"; «руб»/«₽»/«рублей» →
  "руб"; «евро»/«€»/«EUR» → "EUR".
- Цена может быть в прайсе-вложении (таблица/скан) — используй её.
- Формат «АРТИКУЛ: ЦЕНА ВАЛЮТА» (напр. «KM857781G02: 35.80 USD», «EAA5393A006:
  535.90 USD/set», «FBA24270AH34: 189.70 USD») — это ЦЕНА поставщика по позиции.
  Извлеки число и валюту. Артикул перед ценой — обозначение ПОСТАВЩИКА той же
  детали; он может НЕ совпадать с нашим названием/OEM — это нормально.
- Если запрошена ОДНА позиция, а в ответе есть ОДНА числовая цена — привяжи её к
  этой единственной позиции ⇒ "quoted", ДАЖЕ если артикул рядом не совпадает с
  нашим. Не ставь "skipped" из-за несовпадения артикула, когда позиция одна.
  При НЕСКОЛЬКИХ строках «артикул: цена» и нескольких позициях — сопоставь по
  артикулу, иначе по порядку.
- НЕ выдумывай цены и сроки — бери только из ответа/прайса.
- Если по позиции непонятно — "skipped".

Дополнительно определи ИНТЕНТ письма в целом (reply_intent):
- "question_to_us"    — поставщик задал НАМ встречный вопрос и ждёт нашего ответа
                        (просит фото/чертёж, номер лифта, модель, уточнить позицию:
                        «Do you have a photo?», «which model?», «нет номера лифта?»,
                        «подскажите…?»). Мяч на НАШЕЙ стороне.
- "awaiting_supplier" — принял в работу / уточняет у своего поставщика / ещё считает
                        («we are checking», «will keep you posted», «уточняем цену и
                        наличие», «in progress»). Мяч у поставщика.
- "none"              — есть офферы/отказы, или обычный ответ без встречного вопроса.

Верни СТРОГО JSON:
{"reply_intent":"question_to_us|awaiting_supplier|none","offers":[{"index":1,"outcome":"quoted|refused|skipped","price":12345.67,"currency":"руб","valid_until_text":"...","refusal_reason":"...","quote":"..."}]}
По каждой позиции из списка — ровно один объект с её index.
SYS;

        $userText = "ЗАПРОШЕННЫЕ ПОЗИЦИИ:\n{$itemsBlock}\nОТВЕТ ПОСТАВЩИКА (письмо):\n"
            . ($replyText !== '' ? $replyText : '(пусто)');
        if ($attachmentText !== '') {
            $userText .= "\n\nПРАЙС/ОТВЕТ ИЗ ВЛОЖЕНИЙ (текст):\n{$attachmentText}";
        }

        // Без изображений — обычное текстовое сообщение. С изображениями —
        // multimodal content (text + image_url) для Vision.
        if ($images === []) {
            $userContent = $userText;
        } else {
            $userContent = [['type' => 'text', 'text' => $userText]];
            foreach ($images as $img) {
                $userContent[] = ['type' => 'image_url', 'image_url' => ['url' => $img]];
            }
        }

        return [
            ['role' => 'system', 'content' => $system],
            ['role' => 'user', 'content' => $userContent],
        ];
    }
}
