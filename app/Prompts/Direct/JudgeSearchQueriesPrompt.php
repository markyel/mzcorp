<?php

namespace App\Prompts\Direct;

/**
 * Разбор поисковых запросов, по которым показалась наша реклама.
 *
 * Зачем: автотаргетинг Директа подбирает запросы сам, и подбирает широко.
 * Замер 23.09.2026 по нашей кампании: из 39 показов ни одного по нашим
 * фразам, а среди запросов — «регулируемый блок питания распродажа», «опорный
 * поручень для ванной комнаты», «промышленные материнские платы». Каждый такой
 * показ и клик оплачен нами и никогда не станет заявкой.
 *
 * Модель отделяет свой мир от чужого и предлагает минус-фразу — то слово, по
 * которому мусор отсекается целым классом, а не по одному запросу. Решение
 * применяет человек: ошибка в минус-слове молча убивает живой трафик.
 */
class JudgeSearchQueriesPrompt
{
    public static function systemMessage(): string
    {
        return <<<'PROMPT'
Ты разбираешь поисковые запросы, по которым показалась реклама поставщика
запчастей для ЛИФТОВ и ЭСКАЛАТОРОВ (промышленное подъёмное оборудование:
лифты, эскалаторы, траволаторы, подъёмники).

Наш мир — детали и узлы такого оборудования: поручни эскалатора, ступени,
гребёнки, балюстрада, тяговые цепи и ремни, направляющие, башмаки и вкладыши,
двери кабины и шахты, приводы, лебёдки, редукторы, станции управления и платы,
энкодеры, датчики и фотозавесы, кнопки и посты, канаты, ролики, шкивы,
микровыключатели, а также марки Otis, Kone, Schindler, ThyssenKrupp, Sigma,
Fermator, Wittur, Могилёвлифтмаш, ЩЛЗ, КМЗ и подобные.

Чужой мир — всё остальное, даже если слово совпадает:
  • блоки питания, источники питания, радиодетали, материнские платы,
    промышленные компьютеры, каталоги электрики (IEK, ABB) — совпадает код;
  • поручни и опоры для ИНВАЛИДОВ, для ванной, для дома, из ПВХ — совпадает
    слово «поручень», но это медицинские/сантехнические изделия;
  • автозапчасти, велосипеды, бытовая техника, мебель, стройматериалы;
  • вакансии, обучение, ремонт квартир, услуги монтажа не нашего профиля.

Для КАЖДОГО запроса верни объект:
{"query": "<запрос дословно>", "verdict": "ours|foreign|unclear",
 "phrase": "<минус-фраза или null>", "reason": "<до 8 слов>"}

verdict:
  ours — запрос про наше оборудование или его детали;
  foreign — запрос из чужого мира, показ бесполезен;
  unclear — непонятно без контекста (только тогда, когда правда неясно).

phrase — только для foreign: КОРОТКАЯ минус-фраза (1–3 слова) из самого
запроса, которая отсечёт весь класс такого мусора: для «опорный поручень для
ванной комнаты» — «ванной», для «регулируемый блок питания распродажа» —
«блок питания», для «промышленные материнские платы» — «материнские».
НЕ бери слова, которые встречаются и в наших запросах (лифт, эскалатор,
поручень, ремень, плата, цепь, привод, двигатель, кнопка, датчик — сами по
себе НЕЛЬЗЯ). Если такой безопасной минус-фразы нет — верни null и verdict
unclear: пусть решает человек.

Для ours и unclear phrase всегда null.

Ответ — СТРОГО JSON вида {"items": [ ... ]}, по объекту на каждый входной
запрос, в том же порядке. Ничего, кроме JSON.
PROMPT;
    }

    /**
     * @param  array<int, string>  $queries
     */
    public static function userMessage(array $queries): string
    {
        $list = [];
        foreach (array_values($queries) as $i => $query) {
            $list[] = ($i + 1).'. '.$query;
        }

        return "Запросы:\n".implode("\n", $list);
    }
}
