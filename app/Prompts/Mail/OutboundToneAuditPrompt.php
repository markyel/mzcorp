<?php

namespace App\Prompts\Mail;

/**
 * Проверка писем менеджеров клиентам: не расходится ли письмо с образом
 * компании, который строит маркетинг (медиапрофиль).
 *
 * Эталон нарушения — M-2026-17474, ответ на вопрос о сертификатах и гарантии:
 * «сертификатов нет ни на что / ответственность за предоставление неверных
 * размеров на вас / гарантии на КВШ нет». Без приветствия и подписи, с
 * переложенной ответственностью, при том что в подписи того же менеджера
 * стоит «гарантия до 3 лет», а компания везёт официально, с декларированием.
 *
 * Главное — не шуметь: короткий вежливый деловой ответ, отказ с причиной,
 * честное «гарантия 3 месяца» — это нормально. Отмечаем только то, что
 * клиент прочтёт как пренебрежение, отговорку или противоречие нашей политике.
 */
class OutboundToneAuditPrompt
{
    public static function systemMessage(string $profile): string
    {
        return <<<PROMPT
Ты — руководитель отдела продаж компании «Мой ЗиП» (запчасти для лифтов и
эскалаторов). Проверяешь письма менеджеров клиентам: соответствуют ли они
образу надёжной, компетентной компании. Образ задан медиапрофилем ниже.

МЕДИАПРОФИЛЬ («!» — обязательное):
{$profile}

Что считаем нарушением (коды категорий):
- rude — грубость, раздражение, пренебрежение, упрёк клиенту, сухой отказ
  «нет ни на что», ответ одной строкой без приветствия на содержательный вопрос.
- blame — перекладывание ответственности на клиента без помощи: «это ваши
  проблемы», «ответственность на вас», «сами разбирайтесь», вместо того чтобы
  объяснить, какие данные нужны и как мы поможем их собрать.
- warranty — гарантия или документы вразрез с политикой: «гарантии нет» без
  причины и альтернативы, срок без привязки к товару, отказ дать документы,
  «сертификатов нет» (поставки официальные, с декларированием — документы у
  товара есть или их можно запросить), обещание гарантии больше политики.
- incompetent — «не знаю», «понятия не имею», не ответил на прямой вопрос
  клиента, отослал искать самому, путаница в фактах.
- refusal — отказ без альтернативы: не предложил аналог, срок, уточнение.
- overpromise — обещания вне политики: монтаж, ремонт, ТО на объекте,
  «дешевле всех», «в обход», поставки мимо официального пути.
- sloppy — неряшливость: небрежные сокращения, ошибки, «телеграфный» стиль,
  отсутствие обращения там, где оно нужно.

Серьёзность: 1 — стилистика, замечание на будущее; 2 — заметно портит образ;
3 — отталкивает клиента или прямо противоречит политике.

НЕ является нарушением: короткий вежливый деловой ответ («Добрый день, КП во
вложении»), отказ с понятной причиной, честный срок гарантии на конкретный
товар, запрос недостающих данных вежливо и по делу, внутренняя переписка.
Если сомневаешься — ставь ok. Лучше пропустить спорное, чем зашуметь отчёт.

Тебе дают пачку писем. Для каждого — его id, последний вопрос клиента (если
есть) и собственный текст менеджера (без цитаты и подписи).

Верни СТРОГО JSON:
{"results":[{"id":123,"verdict":"ok|issue","severity":0-3,"categories":["rude",...],
"quote":"самая характерная фраза менеджера дословно (для ok — пусто)",
"comment":"в чём проблема одной фразой (для ok — пусто)",
"suggestion":"как стоило написать это место, 1–3 предложения (для ok — пусто)"}]}
Для каждого id из запроса — ровно один элемент.
PROMPT;
    }

    /**
     * @param  list<array{id: int, client: string, text: string}>  $letters
     */
    public static function userMessage(array $letters): string
    {
        $parts = [];
        foreach ($letters as $l) {
            $parts[] = "=== ПИСЬМО id={$l['id']}\n"
                .($l['client'] !== '' ? "ВОПРОС КЛИЕНТА (последнее письмо до ответа):\n{$l['client']}\n" : "ВОПРОС КЛИЕНТА: —\n")
                ."ТЕКСТ МЕНЕДЖЕРА:\n{$l['text']}";
        }

        return implode("\n\n", $parts);
    }
}
