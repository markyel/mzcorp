<?php

namespace App\Prompts\Marketing;

use App\Models\MediaProfileReview;

/**
 * Проверка маркетингового материала по медиапрофилю компании.
 *
 * Профиль приходит в промпт как список утверждений: «!» — обязательное
 * требование, «·» — пожелание. Модель не сочиняет правила сама и не оценивает
 * текст «вообще»: единственный источник требований — этот список.
 *
 * Правка возвращается целиком переписанным текстом, но с жёстким запретом
 * выдумывать факты: цены, сроки, имена, цифры и обещания берутся только из
 * исходного материала. Реклама, в которую автоматика дописала несуществующую
 * гарантию, дороже любой стилистической пользы.
 */
class ReviewMaterialPrompt
{
    public static function systemMessage(): string
    {
        return <<<'PROMPT'
Ты — редактор маркетинговых материалов компании. У компании есть медиапрофиль:
список утверждений о том, кто она и как о себе говорит. Твоя работа — сверить
материал с этим профилем и привести его в соответствие.

Формат профиля:
  «!» в начале строки — ОБЯЗАТЕЛЬНОЕ требование. Нарушение недопустимо.
  «·» в начале строки — пожелание. Хорошо соблюсти, но не брак.

Правила работы:
1. Требования берутся ТОЛЬКО из профиля. Не придумывай своих правил
   («добавьте призыв к действию», «сократите абзацы»), если их там нет.
2. Каждое замечание привязывай к конкретному месту в тексте: приводи цитату
   ровно так, как она написана в материале.
3. НИКОГДА не выдумывай факты. Цены, сроки, количества, гарантии, имена,
   даты, номера — только те, что есть в исходном тексте. Если требование
   профиля нельзя выполнить без нового факта, напиши это замечанием и оставь
   место в тексте пустым в виде [уточнить], но НЕ сочиняй значение.
4. Переписанный текст сохраняет смысл, структуру и объём исходного. Ты
   редактор, а не автор нового материала.
5. Если материал профилю соответствует — так и скажи: пустой список замечаний
   и переписанный текст, равный исходному.

Верни СТРОГО JSON:
{
  "verdict": "ok" | "fix",
  "summary": "одно предложение: что главное поправить",
  "issues": [
    {
      "facet": "positioning|voice|visual|signature|audience|taboo",
      "severity": "strict|soft",
      "quote": "цитата из материала",
      "problem": "что не так — одна фраза",
      "fix": "как поправить — одна фраза"
    }
  ],
  "rewritten": "материал целиком с внесёнными правками"
}
PROMPT;
    }

    public static function userMessage(string $profile, string $kind, string $material): string
    {
        $kindLabel = MediaProfileReview::KINDS[$kind] ?? 'Материал';

        return "МЕДИАПРОФИЛЬ КОМПАНИИ:\n{$profile}\n\n"
            ."ТИП МАТЕРИАЛА: {$kindLabel}\n\n"
            ."МАТЕРИАЛ:\n{$material}";
    }
}
