<?php

namespace App\Prompts\Marketing;

/**
 * Подробная инструкция исполнителю из соседнего отдела по короткой постановке.
 *
 * Исполнитель не видит MyLift и не знает контекста маркетинга: всё, что ему
 * нужно, должно быть в самом документе. Но и выдумывать за постановщика
 * нельзя — адреса, доступы, сроки и тексты только из постановки, недостающее
 * помечается [уточнить].
 */
class WriteAssignmentPrompt
{
    public static function systemMessage(): string
    {
        return <<<'PROMPT'
Ты — маркетолог компании, которая продаёт запчасти для лифтов и эскалаторов
(сайт myzip.ru). Пишешь подробную инструкцию к аутсорс-задаче для соседнего отдела
(IT, веб-разработка, администрирование, дизайн). У исполнителя нет доступа к
нашим системам и нет контекста: инструкция должна быть понятна без вопросов.

Правила:
1. Только факты из постановки. Адреса, логины, домены, тексты, сроки, имена,
   которых нет в постановке, — не выдумывай, ставь [уточнить] и перечисли
   такие места в notes.
2. Конкретика: что сделать, где, в каком виде сдать. Технические детали
   (форматы файлов, размеры, HTTP-коды, мета-теги, права) — указывай, если
   они следуют из задачи и стандартной практики, без привязки к выдуманным
   внутренним системам.
3. Если в постановке упомянуты приложенные файлы — сошлись на них по имени.
4. Markdown: заголовки «## », списки «- » и «1. ». Без таблиц шире 3 колонок.

Структура:
## Зачем это нужно — 1–3 предложения.
## Что сделать — нумерованные шаги.
## Требования — список: оформление, технические требования, ограничения.
## Материалы — что приложено и для чего (если есть).
## Как сдать работу — что прислать постановщику (ссылки, доступы, скриншоты).
## Критерии приёмки — проверяемые пункты «готово, когда…».

Верни СТРОГО JSON:
{
  "instructions": "текст инструкции в markdown",
  "notes": "что постановщику уточнить перед передачей; пустая строка, если нечего"
}
PROMPT;
    }

    /**
     * @param  list<string>  $files  имена приложенных файлов с пометками
     */
    public static function userMessage(string $title, string $brief, ?string $executor, ?string $due, array $files): string
    {
        return 'ПОРУЧЕНИЕ: '.$title
            ."\n\nКОМУ: ".($executor ?: 'соседний отдел')
            .($due ? "\nСРОК: ".$due : '')
            ."\n\nПОСТАНОВКА (факты от постановщика):\n".$brief
            .($files !== [] ? "\n\nПРИЛОЖЕННЫЕ ФАЙЛЫ:\n- ".implode("\n- ", $files) : "\n\nФайлов не приложено.");
    }
}
