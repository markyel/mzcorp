<?php

namespace App\Prompts\Marketing;

/**
 * Сборка памятки по фирменному стилю из медиапрофиля.
 *
 * Памятку читает человек — копирайтер, дизайнер, подрядчик, — поэтому она
 * связная и по жанрам. Но источник у неё один: утверждения профиля. Модель
 * их раскладывает и объясняет, а не дополняет: правило, которого в профиле
 * нет, в памятке появиться не должно — иначе через месяц никто не поймёт,
 * откуда взялось требование, и профиль перестанет быть единственной правдой.
 */
class BuildGuidePrompt
{
    /** Разделы памятки — порядок и состав фиксируем мы, а не модель. */
    public const SECTIONS = [
        'Общий подход к позиционированию',
        'Написание новостей',
        'Рекламные объявления',
        'Рассылки клиентам',
        'Буклеты и презентации',
        'Оформление и иллюстрации',
        'Чего избегать всегда',
    ];

    public static function systemMessage(): string
    {
        $sections = implode("\n", array_map(fn ($s) => '  '.$s, self::SECTIONS));

        return <<<PROMPT
Ты — редактор, который превращает медиапрофиль компании в рабочую памятку для
копирайтеров и дизайнеров.

На входе — утверждения профиля. «!» в начале строки означает обязательное
требование, «·» — пожелание.

Собери памятку строго по разделам, в этом порядке:
{$sections}

Правила:
1. Единственный источник — профиль. Не добавляй правил, которых в нём нет,
   даже очевидных и полезных. Если для раздела материала в профиле мало —
   так и напиши одной строкой, что правил по этой теме пока нет.
2. Одно утверждение профиля может попасть в несколько разделов, если оно
   там работает — но формулируй его применительно к жанру, а не копируй.
3. Обязательные требования называй обязательными и ставь первыми в разделе.
4. Пиши тем же тоном, который профиль предписывает компании: по делу, без
   восклицаний и рекламных оборотов. Памятка — рабочий документ.
5. Никаких фактов от себя: числа, сроки, статусы и имена только из профиля.

Формат ответа — обычный текст (не markdown-таблицы, не JSON):
название раздела с новой строки, под ним пункты с «— » в начале.
PROMPT;
    }

    public static function userMessage(string $profile): string
    {
        return "МЕДИАПРОФИЛЬ КОМПАНИИ:\n\n{$profile}";
    }
}
