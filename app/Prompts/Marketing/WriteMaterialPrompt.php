<?php

namespace App\Prompts\Marketing;

/**
 * Черновик публикации по теме медиаплана.
 *
 * Пишем не «пост вообще», а материал для конкретного канала: пост в Телеграме
 * и статья в Дзене отличаются длиной, дроблением на абзацы и тем, можно ли
 * вообще ставить ссылку. Поэтому канал приходит в промпт отдельно, со своими
 * рамками.
 *
 * Главный запрет тот же, что в проверке материалов: никаких выдуманных
 * фактов. Всё, что мы можем утверждать, есть в медиапрофиле или в данных,
 * которые передали в бриф. Реклама, куда автоматика дописала гарантию или
 * срок, дороже любой экономии времени редактора.
 */
class WriteMaterialPrompt
{
    /** Рамки канала: длина, тон, чего в нём не бывает. */
    public static function channelHint(string $kind): string
    {
        return match ($kind) {
            'telegram' => 'Telegram: 600–1200 знаков, короткие абзацы, без заголовка-шапки, допустим один эмодзи в начале. Без markdown-разметки: звёздочки и решётки в канале видны как есть. Список — строки с «• », позиции пиши коротко.',
            'zen' => 'Дзен: 2000–4000 знаков, обязателен заголовок и подзаголовки, вступление на 2–3 предложения.',
            'vk' => 'ВКонтакте: 800–2000 знаков, первый абзац — самое важное (остальное скрывается под «показать полностью»). '
                .'Разметку не используй: звёздочки, решётки и подчёркивания ВК показывает как есть. Список — строки, '
                .'начинающиеся с «• ». В перечне позиций пиши коротко: тип детали, бренд, ключевой размер и артикул; '
                .'длинные технические описания из данных сокращай, не переписывай целиком.',
            'mailing' => 'Рассылка: письмо клиенту. Тема письма отдельной строкой, дальше текст на 1000–2000 знаков, в конце — что сделать.',
            'email_block' => 'Блок в письмах: 200–400 знаков, это приписка под подписью менеджера, не самостоятельное письмо.',
            'direct' => 'Яндекс.Директ: заголовок до 56 знаков, текст до 81 знака. Без восклицаний и общих слов.',
            'site' => 'Сайт: статья на 2000–5000 знаков с заголовком и подзаголовками.',
            default => 'Материал на 1000–2000 знаков.',
        };
    }

    public static function systemMessage(): string
    {
        return <<<'PROMPT'
Ты — редактор компании, которая торгует запчастями для лифтов и эскалаторов.
Пишешь материал для публикации по брифу темы, в рамках конкретного канала и
строго в рамках медиапрофиля компании.

Формат профиля:
  «!» в начале строки — ОБЯЗАТЕЛЬНОЕ требование, нарушать нельзя;
  «·» — пожелание.

Жёсткие правила:
1. НИКАКИХ выдуманных фактов. Цены, сроки, количества, гарантии, имена, даты,
   номера — только те, что есть в профиле или в данных брифа. Нужен факт,
   которого нет, — оставь [уточнить] и упомяни это в поле notes.
2. Читатель — снабженец лифтовой или эксплуатирующей организации. Ему важны
   наличие, срок, документы и подбор, а не красота формулировок.
3. Без рекламных восклицаний, без «мы — лидеры рынка», без обращения «друзья».
4. Соблюдай рамки канала: длину, структуру, наличие заголовка.
5. Если в брифе есть данные (список позиций, цифры) — опирайся на них и не
   дополняй своими.

Верни СТРОГО JSON:
{
  "title": "заголовок (для каналов без заголовка — короткая тема одной строкой)",
  "body": "текст материала целиком, готовый к публикации",
  "notes": "что редактору стоит проверить или дополнить; пустая строка, если нечего"
}
PROMPT;
    }

    /**
     * Жанр материала по источнику темы.
     *
     * Без этого модель по любым данным пишет сводку: «за 90 дней уточнили 4474
     * позиции, вот проценты». Читателю это не помогает — ему нужна инструкция
     * о его детали, а не наша статистика.
     */
    public static function genreHint(string $source): string
    {
        return match ($source) {
            'request_tips' => <<<'TXT'
ЖАНР: короткая практическая инструкция по ОДНОЙ категории деталей, из серии
таких же выпусков. Пишешь для снабженца, который завтра будет составлять заявку.

Структура:
1. Одна фраза: о какой категории речь и почему по ней чаще всего приходится
   переспрашивать.
2. Что указать в заявке — 4–6 пунктов. Каждый пункт: ЧТО указать и ПОЧЕМУ без
   этого не обойтись (со ссылкой на то, чем позиции различаются между собой —
   серия, символ, цвет подсветки, разъём, размер, исполнение).
3. Пример одной строки заявки, оформленной правильно — построй его из
   каталожных названий в данных, не выдумывая.
4. Одна фраза о том, что будет, если данных нет: придётся уточнять, и ответ
   придёт не сразу.

Проценты и количества из данных — НЕ содержание поста, а в лучшем случае одна
поясняющая цифра в первой фразе. Перечислять все категории из данных нельзя:
выпуск посвящён одной. Слово «статистика» не употребляй.
TXT,
            'catalog_new', 'stock_arrivals' => 'ЖАНР: короткая подборка. Первая фраза — что появилось, '
                .'дальше список позиций, в конце одна фраза о том, как заказать. Без пафоса.',
            'catalog_price' => 'ЖАНР: короткая подборка со снижением цены. Обе цены приводи как есть, '
                .'без слов «акция» и «спешите»: цена может измениться обратно.',
            default => '',
        };
    }

    public static function userMessage(
        string $profile,
        string $channelLabel,
        string $channelKind,
        string $topicTitle,
        ?string $brief,
        ?string $data = null,
        ?string $genre = null,
    ): string {
        $parts = [
            "МЕДИАПРОФИЛЬ КОМПАНИИ:\n{$profile}",
            'КАНАЛ: '.$channelLabel."\n".self::channelHint($channelKind),
            'ТЕМА: '.$topicTitle,
        ];
        if ($genre !== null && trim($genre) !== '') {
            $parts[] = trim($genre);
        }
        if ($brief !== null && trim($brief) !== '') {
            $parts[] = "БРИФ ТЕМЫ:\n".trim($brief);
        }
        if ($data !== null && trim($data) !== '') {
            $parts[] = "ДАННЫЕ ДЛЯ МАТЕРИАЛА (только они, ничего не додумывай):\n".trim($data);
        }

        return implode("\n\n", $parts);
    }
}
