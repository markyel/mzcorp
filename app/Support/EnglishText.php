<?php

namespace App\Support;

/**
 * Английский текст для иностранного поставщика (название позиции в письме-запросе).
 *
 * Перевод держит коды «как написано» — и с ними кириллические буквы-двойники из русского названия: «Rope 250Т»,
 * «sZ с steel core» (20.11.2026, заявка 21116: отправка блокировалась «нет английского названия», хотя на экране всё
 * по-английски). Если вся кириллица в тексте — такие двойники, это английский текст: двойники меняем на латиницу.
 */
final class EnglishText
{
    /** Кириллические буквы, неотличимые от латинских. */
    private const LOOKALIKES = [
        'А' => 'A', 'В' => 'B', 'Е' => 'E', 'К' => 'K', 'М' => 'M', 'Н' => 'H', 'О' => 'O', 'Р' => 'P', 'С' => 'C', 'Т' => 'T',
        'Х' => 'X', 'У' => 'Y', 'а' => 'a', 'е' => 'e', 'о' => 'o', 'р' => 'p', 'с' => 'c', 'у' => 'y', 'х' => 'x', 'к' => 'k', 'м' => 'm',
    ];

    /**
     * Двойники — латиницей, если кроме них кириллицы нет и текст в основном латинский (настоящих латинских букв не
     * меньше трёх и не меньше двойников): русское «Трос» или «Ось» целиком из двойников так английским не станет.
     */
    public static function fold(string $text): string
    {
        $folded = strtr($text, self::LOOKALIKES);
        if ($folded === $text || preg_match('/\p{Cyrillic}/u', $folded) === 1) {
            return $text;
        }
        $latin = preg_match_all('/[A-Za-z]/', $text);
        $lookalikes = preg_match_all('/\p{Cyrillic}/u', $text);

        return $latin >= 3 && $latin >= $lookalikes ? $folded : $text;
    }

    /** Годится англоязычному поставщику: не пусто и без кириллицы (двойники не в счёт). */
    public static function isEnglish(?string $text): bool
    {
        $text = trim((string) $text);

        return $text !== '' && preg_match('/\p{Cyrillic}/u', self::fold($text)) !== 1;
    }
}
