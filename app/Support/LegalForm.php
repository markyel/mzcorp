<?php

namespace App\Support;

/**
 * Организационно-правовая форма в названии организации — всегда сокращённо.
 *
 * Названия контрагентов приходят из разных мест (наши КП и счета, выписка
 * ЕГРЮЛ, веб-форма, ручной ввод), и в реестре жили вперемешку «ИП» и
 * «Индивидуальный Предприниматель», «ООО» и «ОБЩЕСТВО С ОГРАНИЧЕННОЙ
 * ОТВЕТСТВЕННОСТЬЮ», «КОМПЛЕКС СЕРВИС ООО». Заказчик (2026-09-28): хранить
 * везде сокращённую форму.
 *
 * Меняется только форма; само название (регистр, кавычки) остаётся как есть.
 */
final class LegalForm
{
    /** Полная форма (любой регистр, именительный и родительный падеж) => сокращение. Длинные — раньше. */
    private const FULL = [
        'обществ[оа]\s+с\s+ограниченной\s+ответственностью' => 'ООО',
        'обществ[оа]\s+с\s+дополнительной\s+ответственностью' => 'ОДО',
        'публичн(?:ое|ого)\s+акционерн(?:ое|ого)\s+обществ[оа]' => 'ПАО',
        'непубличн(?:ое|ого)\s+акционерн(?:ое|ого)\s+обществ[оа]' => 'АО',
        'закрыт(?:ое|ого)\s+акционерн(?:ое|ого)\s+обществ[оа]' => 'ЗАО',
        'открыт(?:ое|ого)\s+акционерн(?:ое|ого)\s+обществ[оа]' => 'ОАО',
        'акционерн(?:ое|ого)\s+обществ[оа]' => 'АО',
        'акционерн(?:ая|ой)\s+компани[яи]' => 'АК',
        'индивидуальн(?:ый|ого)\s+предпринимател[ья]' => 'ИП',
        'товариществ[оа]\s+собственников\s+жилья' => 'ТСЖ',
        'товариществ[оа]\s+собственников\s+недвижимости' => 'ТСН',
        'автономн(?:ая|ой)\s+некоммерческ(?:ая|ой)\s+организаци[яи]' => 'АНО',
        'некоммерческ(?:ое|ого)\s+партнерств[оа]' => 'НП',
        'федеральн(?:ое|ого)\s+государственн(?:ое|ого)\s+унитарн(?:ое|ого)\s+предприяти[ея]' => 'ФГУП',
        'государственн(?:ое|ого)\s+унитарн(?:ое|ого)\s+предприяти[ея]' => 'ГУП',
        'муниципальн(?:ое|ого)\s+унитарн(?:ое|ого)\s+предприяти[ея]' => 'МУП',
        'частн(?:ое|ого)\s+унитарн(?:ое|ого)\s+предприяти[ея]' => 'ЧУП',
        'федеральн(?:ое|ого)\s+государственн(?:ое|ого)\s+бюджетн(?:ое|ого)\s+учреждени[ея]\s+культуры' => 'ФГБУК',
        'федеральн(?:ое|ого)\s+государственн(?:ое|ого)\s+бюджетн(?:ое|ого)\s+учреждени[ея]' => 'ФГБУ',
        'государственн(?:ое|ого)\s+бюджетн(?:ое|ого)\s+учреждени[ея]\s+здравоохранения' => 'ГБУЗ',
        'государственн(?:ое|ого)\s+бюджетн(?:ое|ого)\s+учреждени[ея]' => 'ГБУ',
        'государственн(?:ое|ого)\s+автономн(?:ое|ого)\s+учреждени[ея]' => 'ГАУ',
        'муниципальн(?:ое|ого)\s+бюджетн(?:ое|ого)\s+учреждени[ея]' => 'МБУ',
        'муниципальн(?:ое|ого)\s+автономн(?:ое|ого)\s+учреждени[ея]' => 'МАУ',
        'жилищно-строительн(?:ый|ого)\s+кооператив[а]?' => 'ЖСК',
        'садоводческ(?:ое|ого)\s+некоммерческ(?:ое|ого)\s+товариществ[оа]' => 'СНТ',
        'потребительск(?:ий|ого)\s+кооператив[а]?' => 'ПК',
        'производственн(?:ый|ого)\s+кооператив[а]?' => 'ПК',
    ];

    /** Сокращения, которые бывают дописаны в конце: «КОМПЛЕКС СЕРВИС ООО». */
    private const SHORT = 'ООО|ОДО|ИП|АО|ЗАО|ПАО|ОАО|НАО|ТСЖ|ТСН|АНО';

    public static function abbreviate(?string $name): ?string
    {
        if ($name === null) {
            return null;
        }
        $out = trim((string) preg_replace('/\s+/u', ' ', $name));
        if ($out === '') {
            return $out;
        }

        foreach (self::FULL as $full => $short) {
            $out = (string) preg_replace('/(?<!\p{L})'.$full.'(?!\p{L})/iu', $short, $out);
        }

        // Форма в конце — в начало: «КОМПЛЕКС СЕРВИС ООО» → «ООО КОМПЛЕКС СЕРВИС»,
        // «Спиридонов Николай Сергеевич ИП (Краснодар)» → «ИП Спиридонов … (Краснодар)».
        if (! preg_match('/^(?:'.self::SHORT.')(?=[\s"«“„]|$)/u', $out)
            && preg_match('/^(.+?)\s+('.self::SHORT.')(\s*\([^()]*\))?$/u', $out, $m)) {
            $out = $m[2].' '.$m[1].($m[3] ?? '');
        }

        // «ООО ООО «МКД-СЕРВИС»» — форма, написанная дважды.
        $out = (string) preg_replace('/^('.self::SHORT.')\s+\1(?=[\s"«“„])/u', '$1', $out);

        return trim($out);
    }
}
